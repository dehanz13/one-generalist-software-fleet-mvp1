// Copy the Supabase migrations into server/schema.ts, so the deployed
// function (whose bundle cannot reach ../supabase) can apply them from the
// Connections page, in order. server/schema.test.ts fails if they ever differ.
//   node scripts/sync-schema.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const folder = join(here, '..', '..', 'supabase', 'migrations')
const target = join(here, '..', 'server', 'schema.ts')

// NNNN_name.sql, applied in number order. Each one records its own number in
// schema_version, so the highest number is the version this build applies.
const files = readdirSync(folder)
  .filter((name) => /^\d{4}_[a-z0-9_]+\.sql$/.test(name))
  .sort()
if (files.length === 0) throw new Error(`no migrations in ${folder}`)

const migrations = files.map((file, index) => {
  const version = Number(file.slice(0, 4))
  if (version !== index + 1) throw new Error(`${file}: migrations are numbered 0001, 0002, … with no gaps`)
  const sql = readFileSync(join(folder, file), 'utf8')
  if (sql.includes('`') || sql.includes('${')) throw new Error(`${file} holds a backtick or \${, which a template literal cannot carry`)
  if (!sql.includes(`values (${version}, `)) throw new Error(`${file} must insert its own version (${version}) into schema_version`)
  return { file, version, sql }
})
const latest = migrations[migrations.length - 1].version

writeFileSync(
  target,
  `// Generated by scripts/sync-schema.mjs from supabase/migrations/*.sql. Do not edit.\n\n` +
    `/** The schema version this build applies. */\nexport const LATEST_SCHEMA_VERSION = ${latest}\n\n` +
    `/** The migrations, run as they are and in order by the Connections page's "Apply schema". */\n` +
    `export const MIGRATIONS: ReadonlyArray<{ file: string; version: number; sql: string }> = [\n` +
    migrations.map((m) => `  {\n    file: '${m.file}',\n    version: ${m.version},\n    sql: \`${m.sql}\`,\n  },\n`).join('') +
    `]\n`,
)
console.log(`wrote ${target} (${files.join(', ')}; latest version ${latest})`)
